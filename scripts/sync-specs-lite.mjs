// Generates src/structures/specs-lite.ts from src/structures/specs.ts so
// pages that only need card metadata and links (/plan.html, src/bridges.ts,
// initial load on walk pages) never pull the full specs prose & 3D geometry
// graph into their first-view JS bundle.
//
// Usage: node scripts/sync-specs-lite.mjs
import { writeFileSync } from 'node:fs';
import { CUBITS, STRUCTURES } from '../src/structures/specs.ts';

const lite = STRUCTURES.map((s) => ({
  id: s.id,
  zh: s.zh,
  en: s.en,
  ref: s.ref,
  ...(s.walk ? { walk: s.walk } : {}),
}));

const out = `// AUTO-GENERATED by scripts/sync-specs-lite.mjs — do not edit by hand.
export type WalkHome =
  | 'ark'
  | 'ezekiel'
  | 'herod'
  | 'nehemiah'
  | 'new-jerusalem'
  | 'palace'
  | 'tabernacle'
  | 'temple';

export interface CubitStandardLite {
  id: string;
  m: number;
}

export const CUBITS: readonly CubitStandardLite[] = ${JSON.stringify(
  CUBITS.map((c) => ({ id: c.id, m: c.m })),
  null,
  2,
)};

export interface StructureLite {
  id: string;
  zh: string;
  en: string;
  ref: string;
  walk?: WalkHome;
}

export const STRUCTURES_LITE: readonly StructureLite[] = ${JSON.stringify(lite, null, 2)};

const WALK_PAGE: Record<WalkHome, string> = {
  ark: '/ark.html',
  ezekiel: '/ezekiel.html',
  herod: '/herod.html',
  nehemiah: '/nehemiah.html',
  'new-jerusalem': '/new-jerusalem.html',
  palace: '/palace.html',
  tabernacle: '/tabernacle.html',
  temple: '/temple.html',
};

/** Where a reader goes to read one card. */
export const measuresHref = (id: string): string => {
  const s = STRUCTURES_LITE.find((x) => x.id === id);
  return \`\${s?.walk ? WALK_PAGE[s.walk] : '/plan.html'}#measures=\${id}\`;
};
`;

writeFileSync(new URL('../src/structures/specs-lite.ts', import.meta.url), out);
console.log(`Synced src/structures/specs-lite.ts (${lite.length} structures)`);
